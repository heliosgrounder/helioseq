"""Pure-Python backend: a line-by-line port of ``src/libushuffle/ushuffle.c``.

Two reasons this exists.

1. ``pip install`` must never fail. If no wheel matches the platform and the C
   extension cannot be compiled, the package still imports and works -- slowly,
   but correctly. Nobody's pipeline breaks because of a missing compiler.

2. It is an executable specification. The port reproduces the C implementation
   *bit for bit*: same xoshiro256++ generator, same order of random draws, same
   graph layout. ``tests/data/golden.json`` is generated by the C harness and
   checked against this module, so a divergence in either implementation is a
   test failure rather than a subtle difference in someone's results.

Roughly 100x slower than the extension. ``helioseq.shuffle.backend()`` reports which one
is in use.
"""

from __future__ import annotations

import os
import time
from typing import List

__all__ = ["ShufflerImpl", "memory_estimate", "BACKEND_NAME"]

BACKEND_NAME = "python"

_MASK64 = (1 << 64) - 1
_MASK32 = (1 << 32) - 1


# --------------------------------------------------------------------------
# xoshiro256++ -- must match prng.h exactly
# --------------------------------------------------------------------------


def _splitmix64(state: int) -> tuple:
    state = (state + 0x9E3779B97F4A7C15) & _MASK64
    z = state
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & _MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & _MASK64
    return state, z ^ (z >> 31)


def _rotl(x: int, k: int) -> int:
    return ((x << k) | (x >> (64 - k))) & _MASK64


class _Rng:
    __slots__ = ("s0", "s1", "s2", "s3")

    def __init__(self, seed: int = 0, stream: int = 0) -> None:
        self.seed(seed, stream)

    def seed(self, seed: int, stream: int = 0) -> None:
        state = (seed & _MASK64) ^ ((stream * 0xD1B54A32D192ED03) & _MASK64)
        values = []
        for _ in range(4):
            state, value = _splitmix64(state)
            values.append(value)
        self.s0, self.s1, self.s2, self.s3 = values
        if not (self.s0 | self.s1 | self.s2 | self.s3):
            self.s0 = 0x9E3779B97F4A7C15

    def next(self) -> int:
        s0, s1, s2, s3 = self.s0, self.s1, self.s2, self.s3
        result = (_rotl((s0 + s3) & _MASK64, 23) + s0) & _MASK64
        t = (s1 << 17) & _MASK64
        s2 ^= s0
        s3 ^= s1
        s1 ^= s2
        s0 ^= s3
        s2 ^= t
        s3 = _rotl(s3, 45)
        self.s0, self.s1, self.s2, self.s3 = s0, s1, s2, s3
        return result

    def below(self, n: int) -> int:
        """Uniform integer in ``[0, n)`` by masked rejection -- no modulo bias."""
        if n <= 1:
            return 0
        mask = n - 1
        mask |= mask >> 1
        mask |= mask >> 2
        mask |= mask >> 4
        mask |= mask >> 8
        mask |= mask >> 16
        mask |= mask >> 32
        while True:
            value = self.next() & mask
            if value < n:
                return value


