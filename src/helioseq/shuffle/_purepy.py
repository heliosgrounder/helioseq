def memory_estimate(length: int, k: int) -> int:
    """Peak bytes the C backend allocates for ``prepare``; see ushuffle.h."""
    if length <= 0 or k <= 1 or k >= length:
        return max(length, 0)
    n_lets = length - k + 2
    return length + n_lets * 12 + n_lets * 4 + n_lets * 20 + n_lets + n_lets * 4


class ShufflerImpl:
    """Backend-level shuffler. Operates on ``bytes`` only; text handling and
    argument validation live in :mod:`helioseq.shuffle.shuffler`."""

    __slots__ = (
        "_rng",
        "_seq",
        "_l",
        "_k",
        "_prepared",
        "_v_offset",
        "_v_n",
        "_v_cursor",
        "_v_seqpos",
        "_v_next",
        "_intree",
        "_indices",
        "_n_vertices",
        "_root",
    )

    def __init__(self, seed: int | None = None, stream: int = 0) -> None:
        if seed is None:
            seed = (
                (time.time_ns() & _MASK64)
                ^ (os.getpid() * 0x9E3779B97F4A7C15)
                ^ (id(self) & _MASK64)
            ) & _MASK64
        self._rng = _Rng(seed, stream)
        self._seq = b""
        self._l = 0
        self._k = 0
        self._prepared = False
        self._n_vertices = 0
        self._root = 0
        self._indices: List[int] = []
        self._v_offset: List[int] = []
        self._v_n: List[int] = []
        self._v_cursor: List[int] = []
        self._v_seqpos: List[int] = []
        self._v_next: List[int] = []
        self._intree: bytearray = bytearray()

    # -- introspection ----------------------------------------------------

    @property
    def length(self) -> int:
        return self._l

    @property
    def k(self) -> int:
        return self._k

    @property
    def n_vertices(self) -> int:
        return self._n_vertices

    def seed(self, seed: int, stream: int = 0) -> None:
        self._rng.seed(seed & _MASK64, stream & _MASK64)

    # -- prepare ----------------------------------------------------------

    def prepare(self, seq: bytes, k: int) -> None:
        if k < 1:
            raise ValueError("k must be >= 1")
        self._seq = bytes(seq)
        self._l = len(self._seq)
        self._k = k
        self._prepared = True
        self._n_vertices = 0
        self._root = 0

        if k >= self._l or k <= 1:
            return  # handled directly in generate()

        self._build_graph()

    def _build_graph(self) -> None:
        seq = self._seq
        k = self._k
        n_lets = self._l - k + 2

        # Vertex ids are handed out in order of first occurrence -- exactly what
        # the C hash table does, so a dict is a faithful stand-in.
        vertex_of: dict = {}
        let_vertex = [0] * n_lets
        v_seqpos: List[int] = []
        v_n: List[int] = []

        for i in range(n_lets):
            key = seq[i : i + k - 1]
            vid = vertex_of.get(key)
            if vid is None:
                vid = len(v_seqpos)
                vertex_of[key] = vid
                v_seqpos.append(i)
                v_n.append(0)
            let_vertex[i] = vid
            if i < n_lets - 1:
                v_n[vid] += 1

        n_vertices = len(v_seqpos)
        root = let_vertex[n_lets - 1]

        offset = 0
        v_offset = [0] * n_vertices
        for vid in range(n_vertices):
            v_offset[vid] = offset
            offset += v_n[vid]

        cursor = [0] * n_vertices
        indices = [0] * (n_lets - 1)
        for i in range(n_lets - 1):
            vid = let_vertex[i]
            indices[v_offset[vid] + cursor[vid]] = let_vertex[i + 1]
            cursor[vid] += 1

        for vid in range(n_vertices):
            if v_n[vid] == 0 and vid != root:
                self._prepared = False
                raise RuntimeError(
                    "internal invariant violated: non-root sink vertex; "
                    "please report this with the input sequence"
                )

        self._n_vertices = n_vertices
        self._root = root
        self._indices = indices
        self._v_offset = v_offset
        self._v_n = v_n
        self._v_cursor = [0] * n_vertices
        self._v_seqpos = v_seqpos
        self._v_next = [0] * n_vertices
        self._intree = bytearray(n_vertices)

    # -- generate ---------------------------------------------------------

    def generate(self) -> bytes:
        if not self._prepared:
            raise RuntimeError("no prepared sequence; call prepare() first")
        if self._l == 0:
            return b""

        k = self._k
        seq = self._seq
        length = self._l

        if k >= length:
            return seq
        if k <= 1:
            out = bytearray(seq)
            rng = self._rng
            for i in range(length - 1, 0, -1):
                j = rng.below(i + 1)
                out[i], out[j] = out[j], out[i]
            return bytes(out)

        rng = self._rng
        v_offset = self._v_offset
        v_n = self._v_n
        v_next = self._v_next
        indices = self._indices
        intree = self._intree
        root = self._root
        n_vertices = self._n_vertices

        # Wilson's algorithm: uniformly random spanning arborescence into root.
        for i in range(n_vertices):
            intree[i] = 0
        intree[root] = 1
        for start in range(n_vertices):
            u = start
            while not intree[u]:
                choice = rng.below(v_n[u])
                v_next[u] = choice
                u = indices[v_offset[u] + choice]
            u = start
            while not intree[u]:
                intree[u] = 1
                u = indices[v_offset[u] + v_next[u]]

        # Order each vertex's out-edges: arborescence edge last, rest uniform.
        for vid in range(n_vertices):
            base = v_offset[vid]
            n = v_n[vid]
            if vid != root and n > 0:
                last = base + n - 1
                chosen = base + v_next[vid]
                indices[last], indices[chosen] = indices[chosen], indices[last]
                limit = n - 1
            else:
                limit = n
            for i in range(limit - 1, 0, -1):
                j = rng.below(i + 1)
                indices[base + i], indices[base + j] = (
                    indices[base + j],
                    indices[base + i],
                )
            self._v_cursor[vid] = 0

        # Walk: the first (k-1)-let is fixed, each edge appends one character.
        out = bytearray(seq[: k - 1])
        cursor = self._v_cursor
        v_seqpos = self._v_seqpos
        u = 0
        while cursor[u] < v_n[u]:
            v = indices[v_offset[u] + cursor[u]]
            out.append(seq[v_seqpos[v] + k - 2])
            cursor[u] += 1
            u = v

        if len(out) != length:
            raise RuntimeError(
                "internal invariant violated: walk consumed %d of %d edges"
                % (len(out), length)
            )
        return bytes(out)
